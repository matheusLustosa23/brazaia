from collections.abc import AsyncIterator
from typing import Any, Protocol, runtime_checkable

from domain.entities.message import Completion
from domain.entities.cerebro import Entidade, Observacao, Registro, Relacao
from domain.entities.device import Device, Localizacao
from domain.tools.base import Tool
from pydantic import BaseModel

@runtime_checkable
class LLMClient(Protocol):
    """Contrato do engine. `application/` depende disto, nunca do `openai`.

    Implementado por `infrastructure.llm.client.OpenAILLMClient` e por fakes nos testes.
    """
    
    async def complete(
        self,
        messages: list[dict],
        tools: list[dict] | None = None,
        tool_choice: str | dict = "auto",
        **opts: Any
    ) -> Completion: ...
    
    def stream(
        self,
        messages: list[dict],
        tools: list[dict] | None = None,
        tool_choice: str = "auto",
        **opts: Any
        ) -> AsyncIterator[tuple[str, Any]]: ...
    
    async def health(self) -> dict: ...
    
@runtime_checkable
class CerebroStore(Protocol):
    """Persistência do cérebro (entidades/observações/relações). Implementado por infrastructure.memory.cerebro_store."""

    async def init(self) -> None: ...
    async def entidade(self, nome: str, tipo: str | None = None) -> Entidade: ...
    async def achar_entidade(self, nome: str) -> Entidade | None: ...
    async def observar(self, entidade_id: int, categoria: str, texto: str, *, substitui: int | None = None,
                       fonte: str = "") -> tuple[Observacao, str]: ...
    async def observacao(self, obs_id: int) -> Observacao | None: ...
    async def invalidar(self, obs_id: int) -> bool: ...
    async def relacionar(self, de_id: int, tipo: str, para_id: int) -> str: ...
    async def da_entidade(self, entidade_id: int, *, incluir_antigas: bool = False) -> list[Observacao]: ...
    async def relacoes(self, entidade_id: int) -> list[Relacao]: ...
    async def buscar(self, termos: list[str], limite: int = 30) -> list[Observacao]: ...
    async def registrar(self, tipo: str, quando: float, *, entidade_id: int | None, dados: dict, texto: str = "",
                        sessao: int | None = None, eh_sessao: bool = False, substitui: int | None = None,
                        fonte: str = "") -> Registro: ...
    async def registro(self, reg_id: int) -> Registro | None: ...
    async def fechar_sessao(self, reg_id: int, fim: float) -> None: ...
    async def sessao_aberta(self, desde: float) -> Registro | None: ...
    async def registros(self, *, tipo: str | None = None, entidade_id: int | None = None, sessao: int | None = None,
                        desde: float | None = None, ate: float | None = None, limite: int = 50) -> list[Registro]: ...

class DeviceRegistry(Protocol):
    """Contrato de persistência de devices."""
    async def init(self) -> None: ...
    async def get(self, device_id: str) -> Device | None: ...
    async def upsert(self, device: Device) -> None: ...
    async def list_all(self) -> list[Device]: ...
    async def set_status(self, device_id: str, status: str) -> None: ...
    async def salvar_localizacoes(self, pontos: list[Localizacao]) -> int: ...
    async def localizacoes(self, device_id: str, desde: float | None = None, limite: int = 500) -> list[Localizacao]: ...
    async def ultima_localizacao(self, device_id: str) -> Localizacao | None: ...


class DeviceGateway(Protocol):
    """Gateway RPC over WebSocket — facade de conexão + dispatch."""
    async def dispatch(self, device_id: str | None, tool: Tool, payload: BaseModel) -> str: ...
    async def capabilities(self, device_id: str | None) -> set[str] | None: ...

class SessionStore(Protocol):
    """Contrato de sessões. Injetado no Orchestrator (application service)."""
    async def create(self) -> str: ...
    async def get(self, session_id: str) -> list[dict]: ...
    async def append(self, session_id: str, message: dict) -> None: ...
    async def set(self, session_id: str, history: list[dict]) -> None: ...
    async def list_sessions(self) -> list[dict]: ...
    async def get_narrative(self, session_id: str) -> list[dict]: ...
    async def append_narrative(self, session_id: str, card: dict) -> None: ...
    async def get_meta(self, session_id: str) -> dict: ...
    async def set_meta(self, session_id: str, *, titulo: str | None = None, tags: list[str] | None = None,
                       modo: str | None = None) -> None: ...
    
